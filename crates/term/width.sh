#!/bin/sh
# Writes src/width_table.rs: the cells a character takes, from glibc's UTF-8 charmap, so lp-term
# counts as the shell's programs do through wcwidth. The ranges are Unicode's data, by the rules
# the charmap's comments give: marks and default-ignorables 0, East Asian wide and fullwidth 2,
# the rest 1. Run from this folder; Debian's `locales` package has the charmap.
set -eu
src=${1:-/usr/share/i18n/charmaps/UTF-8.gz}
version=$(zcat "$src" | sed -n 's/^% Character width according to Unicode \([0-9.]*\)\.$/\1/p')
{
  echo "// Generated by width.sh from glibc's UTF-8 charmap (Unicode $version). Don't edit by hand."
  echo
  echo "/// The Unicode version the table is from."
  echo "pub const UNICODE: &str = \"$version\";"
  echo
  echo "/// \`(first, last, width)\`, sorted. A character in none of them is 1 wide."
  echo "pub(crate) static WIDTHS: &[(u32, u32, u8)] = &["
  zcat "$src" | sed -n '/^WIDTH$/,/^END WIDTH$/p' | sed '1d;$d' |
    sed -E 's/^<U([0-9A-F]+)>\.\.\.<U([0-9A-F]+)>[[:space:]]+([0-9])$/    (0x\1, 0x\2, \3),/;
            s/^<U([0-9A-F]+)>[[:space:]]+([0-9])$/    (0x\1, 0x\1, \2),/'
  echo "];"
} > src/width_table.rs
